// Integration check against the running REA Studio WebView2, with a dedicated test profile.
// npm install playwright-core@1.58.2 in a separate test directory; set QUIXI_TEST_PLAYWRIGHT_MODULE.
const { chromium } = require(process.env.QUIXI_TEST_PLAYWRIGHT_MODULE || 'playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {version} = require('./version.cjs');
const {showPanel, revealDetails, showAnalysisSection} = require('./ui-test-navigation.cjs');
(async()=>{
  const browser=await chromium.connectOverCDP(process.env.REA_STUDIO_TEST_CDP || 'http://127.0.0.1:9322');
  const page=browser.contexts()[0].pages().find(p=>p.url().includes('app.localhost/playground'));
  assert(page,'REA Studio playground webview was not found');
  page.setDefaultTimeout(20000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const call=(route,data={})=>page.evaluate(async({route,data})=>{const r=await fetch('/api/quixi/playground/'+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});const v=await r.json();if(!r.ok)throw new Error(JSON.stringify(v));return v;},{route,data});
  const runOracleThroughUi=async()=>{
    await showAnalysisSection(page,'reconstruction-panel');await revealDetails(page,'#oracle-run');
    await page.locator('#oracle-run').click();
    await page.locator('#oracle-consent').waitFor({state:'visible'});
    assert.match(await page.locator('#oracle-consent-sha').textContent(),/[a-f0-9]{64}/i);
    await page.locator('#oracle-approve').click();
    await page.locator('#oracle-consent').waitFor({state:'hidden'});
    await page.locator('#oracle-result').waitFor({state:'visible'});
    await page.waitForFunction(()=>!state.rea.oracleOperation && state.rea.oracle && ['passed','failed','unverified'].includes(state.rea.oracle.status));
  };
  const readDisplayedRecord=async(tool,offset=null,expectedId=null)=>{
    try {
      await page.waitForFunction(({tool,offset,expectedId})=>{
        const record=state.rea.record,view=record && QuixiAnalysis.nativeView(unwrap(record.response));
        const matches=record?.tool===tool || (record?.tool==='inspect_analysis_view' && view?.parent_operation===tool);
        return !state.rea.operation && matches && (expectedId===null || record.id===expectedId) && (offset===null || record.arguments?.view?.offset===offset);
      },{tool,offset,expectedId});
    } catch(error) {
      const diagnostics=await page.evaluate(()=>({operation:state.rea.operation,tool:state.rea.record?.tool,
        arguments:state.rea.record?.arguments,view:state.rea.record && QuixiAnalysis.nativeView(unwrap(state.rea.record.response)),
        health:document.getElementById('rea-health').textContent}));
      error.message+='\nDisplayed-record diagnostics: '+JSON.stringify(diagnostics);throw error;
    }
    await revealDetails(page,'#evidence-raw');
    await page.waitForFunction(expectedId=>{try{const record=JSON.parse(document.getElementById('rea-output').textContent);return !!record.tool && (expectedId===null || record.id===expectedId);}catch{return false;}},expectedId);
    return JSON.parse(await page.locator('#rea-output').textContent());
  };
  const root=process.env.QUIXI_SMOKE_ROOT;
  assert(root,'Set QUIXI_SMOKE_ROOT to a dedicated fixture project with README.md, app.js and quixi-fixture.exe');
  const project=await call('project',{path:root});
  await page.reload();await page.locator('#connection').filter({hasText:'Connected'}).waitFor();
  await showPanel(page,'explorer');await page.locator('#project').selectOption(project.id);
  await page.locator('.file-row').filter({hasText:'README.md'}).click();
  await page.locator('#editor').fill('# QuixiDesk verification project\n\nEdited in the native Windows playground.\n');
  await page.locator('#save').click();
  await page.waitForFunction(()=>document.getElementById('dirty').hidden);
  assert(fs.readFileSync(root+'\\README.md','utf8').includes('Edited in the native Windows playground.'));
  const read=await call('read',{project:project.id,path:'README.md'});
  fs.appendFileSync(root+'\\README.md','external edit\n');
  const conflict=await page.evaluate(async({project,hash})=>{const r=await fetch('/api/quixi/playground/write',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({project,path:'README.md',hash,content:'overwrite'})});return{status:r.status,body:await r.json()};},{project:project.id,hash:read.hash});
  assert.equal(conflict.status,400);assert.match(conflict.body.error,/changed on disk/);
  await page.locator('[data-view=changes]').click();await page.waitForFunction(()=>document.getElementById('diff').textContent.includes('Edited in the native'));
  await page.locator('[data-console=terminal]').click();await page.locator('#terminal-command').fill("Write-Output 'native PowerShell works'");await page.locator('#terminal-send').click();
  await page.waitForFunction(()=>document.getElementById('terminal-output').textContent.includes('Exit code: 0'));
  assert.match(await page.locator('#terminal-output').textContent(),/native PowerShell works/);
  await showAnalysisSection(page,'analysis-advanced-tools');await revealDetails(page,'#rea-runtime');await page.locator('#rea-runtime').selectOption('bundled');
  await page.waitForFunction(()=>document.getElementById('rea-badge').textContent==='Connected',{},{timeout:90000});
  console.log('UI: edit, conflict detection, diff, PowerShell and bundled REA connection passed');
  const connected=await call('rea/connect',{mode:'bundled'});fs.writeFileSync(root+'\\rea-catalog.json',JSON.stringify(connected,null,2));
  assert(connected.tools.some(t=>t.name==='open_binary'));assert(connected.session.result?.tool_availability?.groups?.length,'Live availability must be present');
  assert(connected.tools.some(t=>t.name==='procedure_pseudo_code'));
  await call('rea/select',{path:root+'\\quixi-fixture.exe'});
  await showAnalysisSection(page,'analysis-workspace');
  await page.waitForFunction(()=>document.getElementById('artifact-name').textContent==='quixi-fixture.exe');
  await page.locator('[data-rea-tool=open_binary]').click();await page.locator('#rea-run').click();
  await page.waitForFunction(()=>document.getElementById('rea-run').textContent.includes('Run analysis') && !document.getElementById('rea-run').disabled,{},{timeout:90000});
  assert.match(await page.locator('#evidence-summary').textContent(),/Analysis saved/);
  assert.equal(await page.title(),`REA Studio V${version} · Coding & Reverse Engineering`);
  await page.locator('[data-rea-tool=search_strings]').click();
  assert.equal(await page.locator('#rea-run').isDisabled(),true);
  assert.match(await page.locator('#rea-validation').textContent(),/enter text/);
  await page.locator('#rea-input-pattern').fill('quixi');
  assert.equal(JSON.parse(await page.locator('#rea-arguments').inputValue()).pattern,'quixi');
  await page.locator('#rea-connect').click();
  await page.waitForFunction(()=>!document.getElementById('rea-connect').disabled);
  assert.equal(await page.locator('#rea-input-pattern').inputValue(),'quixi');
  if(await page.locator('#analysis-expert-toggle').getAttribute('aria-pressed')!=='true')await page.locator('#analysis-expert-toggle').click();
  await revealDetails(page,'#rea-arguments');
  await page.locator('#rea-arguments').fill('{"pattern":"from JSON","detail":"summary"}');
  assert.equal(await page.locator('#rea-input-pattern').inputValue(),'from JSON');
  await page.locator('[data-rea-tool=procedure_pseudo_code]').click();
  assert.equal(await page.locator('#rea-run').isDisabled(),true);
  await page.locator('[data-rea-tool=list_procedures]').click();await page.locator('#rea-run').click();
  await page.locator('.inventory-table').waitFor({timeout:90000});
  await page.waitForFunction(()=>!document.getElementById('rea-run').disabled);
  const inventory=await readDisplayedRecord('list_procedures');
  assert.equal(inventory.failed,false);
  assert.equal(inventory.response.structuredContent.normalized_result.parent_operation,'list_procedures');
  const retained=inventory.response.structuredContent.normalized_result.parent_evidence_id;
  await page.evaluate(async retained=>{await executeAnalysis('inspect_analysis_view',{source:{kind:'retained-evidence',evidence_id:retained},view:{kind:'native-inventory',offset:0,limit:1}},false);},retained);
  assert.equal(await page.locator('.inventory-table tbody tr').count(),1);
  await page.locator('.inventory-pagination button').filter({hasText:'Next page'}).click();
  await readDisplayedRecord('inspect_analysis_view',1);
  await page.waitForFunction(()=>!document.querySelector('.inventory-pagination button').disabled);
  await page.locator('.inventory-pagination button').filter({hasText:'Previous page'}).click();
  await readDisplayedRecord('inspect_analysis_view',0);
  await page.waitForFunction(()=>!document.querySelector('.inventory-pagination button').disabled);
  await page.locator('[data-rea-tool=search_procedures]').click();await page.locator('#rea-input-pattern').fill('quixi_add');await page.locator('#rea-run').click();
  await page.locator('.inventory-table tbody tr').filter({hasText:'quixi_add'}).waitFor({timeout:90000});
  await page.locator('.inventory-table tbody tr').filter({hasText:'quixi_add'}).getByRole('button',{name:'Decompile'}).click();
  await page.waitForFunction(()=>document.getElementById('recovered-code').textContent.includes('return'),{},{timeout:90000});
  console.log('REA Studio: branding, guided inputs, refresh preservation, real inventory paging and row decompilation passed');
  const native=await call('rea/tool',{tool:'analyze_function',arguments:{procedure:'quixi_add'}});
  fs.writeFileSync(root+'\\rea-native.json',JSON.stringify(native,null,2));assert.equal(native.failed,false,JSON.stringify(native).slice(0,2000));
  const code=await call('rea/tool',{tool:'procedure_pseudo_code',arguments:{procedure:'quixi_add'}});
  fs.writeFileSync(root+'\\rea-decompile.json',JSON.stringify(code,null,2));assert.equal(code.failed,false,JSON.stringify(code).slice(0,2000));
  assert.match(JSON.stringify(code),/return/);
  console.log('REA: real native function analysis and decompilation passed in one persistent MCP session');
  const js=await call('rea/tool',{tool:'analyze_javascript_application',arguments:{input_path:root,detail:'summary'}});
  fs.writeFileSync(root+'\\rea-javascript.json',JSON.stringify(js,null,2));assert.equal(js.failed,false,JSON.stringify(js).slice(0,2000));
  await showAnalysisSection(page,'analysis-evidence');await revealDetails(page,'#rea-record');await page.locator('#rea-record').selectOption(code.id);
  await readDisplayedRecord('procedure_pseudo_code',null,code.id);
  const recovered=await call('rea/evidence',{id:code.id});assert.deepEqual(recovered,code);
  await showAnalysisSection(page,'analysis-advanced-tools');await revealDetails(page,'#toolchain-open');await page.locator('#toolchain-open').click();
  const inventoryTools=await call('toolchain/inventory');
  for(const id of ['rea','ghidra','ida-headless','ida-bridge','x64dbg','workflows']) {
    assert(inventoryTools.tools.some(tool=>tool.id===id),`Expected toolchain entry ${id}`);
  }
  await page.waitForFunction(count=>document.querySelectorAll('.toolchain-row').length===count,inventoryTools.tools.length);
  await page.locator('#toolchain-dialog summary').filter({hasText:'Bundled REA workflows'}).click();
  await page.locator('#workflow-read').click();
  await page.waitForFunction(()=>document.getElementById('workflow-content').textContent.includes('rea-agents 6.8.0'));
  await page.locator('#toolchain-close').click();
  const destination=root+'-rebuild';fs.mkdirSync(destination,{recursive:true});
  const rebuild=await call('project',{path:destination});
  await page.reload();await page.locator('#connection').filter({hasText:'Connected'}).waitFor();
  await showPanel(page,'explorer');await page.locator('#project').selectOption(rebuild.id);
  await showAnalysisSection(page,'reconstruction-panel');await revealDetails(page,'#reconstruction-goal');
  await page.locator('#reconstruction-goal').fill('Rebuild the quixi_add integer addition feature.');
  await page.locator('#reconstruction-analyse').click();
  await page.waitForFunction(()=>document.getElementById('task').value.startsWith('[Reconstruction brief]'));
  assert.equal(await page.locator('#mode').inputValue(),'ask');
  assert.equal(await page.locator('#rea-enabled').isChecked(),true);
  assert.match(await page.locator('#task').inputValue(),/functional SPEC.md draft/);
  await showAnalysisSection(page,'reconstruction-panel');await revealDetails(page,'#reconstruction-export');
  await page.locator('#reconstruction-export').click();
  await page.waitForFunction(()=>document.getElementById('reconstruction-status').textContent.includes('Saved SPEC.md'));
  await page.waitForFunction(()=>document.getElementById('reconstruction-dossier').value && !document.getElementById('oracle-run').disabled);
  const dossier=await page.locator('#reconstruction-dossier').inputValue();assert(dossier);
  const manifest=JSON.parse(fs.readFileSync(destination+'\\'+dossier+'\\manifest.json','utf8'));
  assert(manifest.records.some(r=>r.id===native.id));assert(!manifest.records.some(r=>r.id===js.id));
  assert(fs.existsSync(destination+'\\'+dossier+'\\SPEC.md'));
  await showPanel(page,'settings');await page.locator('#mode').selectOption('code');await runOracleThroughUi();
  await page.waitForFunction(()=>document.getElementById('oracle-result').textContent.includes('unverified'));
  const calc=destination+'\\calc.ps1';fs.writeFileSync(calc,"param([int]$a,[int]$b)\n[Console]::Write($a+$b+1)\n");
  const config=destination+'\\'+dossier+'\\oracle-cases.json';
  fs.writeFileSync(config,JSON.stringify({version:1,cases:[{id:'addition',requirement:'REQ-001',command:"& '.\\calc.ps1' 19 23",expectationSource:'Compiled quixi_add fixture arithmetic: 19 + 23 = 42',expected:{exitCode:0,stdout:'42',stderr:''}}]}));
  await runOracleThroughUi();
  await page.waitForFunction(()=>document.getElementById('oracle-result').textContent.includes('stdout differs'));
  assert.equal(await page.locator('#oracle-retry').isDisabled(),false);
  await page.locator('#oracle-retry').click();assert.equal(await page.locator('#rea-enabled').isChecked(),false);
  assert.match(await page.locator('#task').inputValue(),/actual oracle failure report/);
  fs.writeFileSync(calc,"param([int]$a,[int]$b)\n[Console]::Write($a+$b)\n");
  await page.locator('[data-view=analysis]').click();await runOracleThroughUi();
  await page.waitForFunction(()=>{try{return JSON.parse(document.getElementById('oracle-result').textContent).status==='passed';}catch{return false;}});
  const oracle=JSON.parse(await page.locator('#oracle-result').textContent());assert.equal(oracle.passed,1);
  assert(fs.existsSync(destination+'\\'+oracle.reportPath));
  console.log('Reconstruction: real evidence dossier, unverified empty suite, failing output, retry handoff and passing repaired fixture verified');
  await page.screenshot({path:root+'\\quixidesk-analysis.png'});
  await page.locator('[data-view=overview]').click();await page.screenshot({path:root+'\\quixidesk-playground.png'});
  assert.deepEqual(errors,[],'Unexpected JavaScript errors');
  await call('rea/tool',{tool:'close_binary',arguments:{}});
  console.log(JSON.stringify({passed:true,tools:connected.tools.length,nativeRecord:native.id,decompileRecord:code.id,javascriptRecord:js.id,jsErrors:errors}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
